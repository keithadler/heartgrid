"""Pick the 12-room curriculum from the generated candidates and write everything derived from it:

    levels.json              the single source of truth (maps, solutions, optimal lengths, world layout)
    web/levels.js            the same data for the game
    HeartGrid/Rooms/R*.lean  one Lean file per room (map, solution, solvability + optimality proofs)
    HeartGrid/Prelude.lean, HeartGrid/Levels.lean   shared lemmas and the `curriculum` theorem

usage (from the project root): python3 tools/build_levels.py [candidates_dir]      (default tools/candidates)
Needs the candidate files made by tools/generate_rooms.py (see `make levels`)."""
import json, glob, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from rules import parse, run, won

os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))   # work from the project root

SCR = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'candidates')
NAMES = ["Doorstep", "First Emerald", "Bridge the Gap", "The Watcher", "Moat Walk", "Twin Patrols",
         "Eyes in the Dark", "Stepping Stones", "Gauntlet", "The Long Way", "Hall of Hunters", "The Last Door"]
EXITS = "RRRDLLLDRRRR"          # which wall each room's exit is on; the next room is entered from the opposite wall
OPP = {'U': 'D', 'D': 'U', 'L': 'R', 'R': 'L'}; STEP = {'U': (0, -1), 'D': (0, 1), 'L': (-1, 0), 'R': (1, 0)}

cands = {i: [] for i in range(12)}
for f in glob.glob(SCR + '/*.jsonl'):
    for line in open(f):
        d = json.loads(line); cands[d['slot']].append(d)
late = [c for i in (9, 10, 11) for c in cands[i]]          # rooms 10-12 share sides (L -> R) and parameters
for i in (9, 10, 11): cands[i] = late
for i in range(1, 6): cands[i] = [c for c in cands[i] if c['pushes'] >= 1]
FIRST = 15

# backward pass: leave head-room so later rooms can still be longer
U = [0] * 12
for i in range(11, -1, -1):
    top = max(c['opt'] for c in cands[i]); U[i] = min(top, U[i + 1] - 3) if i < 11 else top
chosen, prev = [], 0
for i in range(12):
    target = FIRST + (U[11] - FIRST) * i / 11
    pool = [c for c in cands[i] if prev + 3 <= c['opt'] <= U[i]]
    if not pool: sys.exit(f'no candidate for slot {i} (prev opt {prev}, cap {U[i]})')
    pool.sort(key=lambda c: (abs(c['opt'] - target) // 4, -min(c['pushes'], 4), c['states']))
    c = pool[0]; chosen.append(c); prev = c['opt']
    print(i + 1, NAMES[i], 'opt', c['opt'], 'pushes', c['pushes'], 'states', c['states'])

out, x, y = [], 0, 0
for i, c in enumerate(chosen):
    L = parse(c['rows']); assert won(L, run(L, c['sol'])) and len(c['sol']) == c['opt']
    out.append(dict(n=i + 1, name=NAMES[i], rows=c['rows'], sol=c['sol'], opt=c['opt'], states=c['states'],
                    enter='L' if i == 0 else OPP[EXITS[i - 1]], exit=EXITS[i], x=x, y=y))
    dx, dy = STEP[EXITS[i]]; x += dx; y += dy
json.dump(out, open('levels.json', 'w'), indent=1)

# ---------------- emit Lean + JS ----------------
KERNEL_MAX_STATES = 100      # small searches are checked by the kernel itself; bigger ones by compiled code
def pl(ps): return '[' + ', '.join(f'({r}, {c})' for r, c in ps) + ']'
DIRN = {'U': '.U', 'D': '.D', 'L': '.L', 'R': '.R'}
GEN = '/-! GENERATED by tools/build_levels.py - do not edit.  Source of truth: levels.json. -/'
os.makedirs('HeartGrid/Rooms', exist_ok=True)
open('HeartGrid/Prelude.lean', 'w').write("""import HeartGrid.Rules
import HeartGrid.Bfs
import HeartGrid.BfsFast
""" + GEN + """
namespace HeartGrid

/-- Read a move string (`U D L R` step, anything else waits). -/
def acts (s : String) : List Act :=
  s.toList.map fun | 'U' => .go .U | 'D' => .go .D | 'L' => .go .L | 'R' => .go .R | _ => .wait

/-- `n` is the exact minimum number of actions needed to solve `L`. -/
def MinMoves (L : Level) (n : Nat) : Prop :=
  (∃ ms, ms.length = n ∧ Solves L ms) ∧ ∀ ms, Solves L ms → n ≤ ms.length

theorem minMoves_of (L : Level) (sol : List Act) (hs : Solves L sol)
    (hno : bfsNoWin L (sol.length - 1) = true) : MinMoves L sol.length :=
  ⟨⟨sol, rfl, hs⟩, fun ms hms => by
    cases Nat.lt_or_ge ms.length sol.length with
    | inl h => exact absurd hms (no_short_solution L (sol.length - 1) hno ms (by omega))
    | inr h => exact h⟩

theorem minMoves_of_h (L : Level) (sol : List Act) (hs : Solves L sol)
    (hno : bfsNoWinH L (sol.length - 1) = true) : MinMoves L sol.length :=
  ⟨⟨sol, rfl, hs⟩, fun ms hms => by
    cases Nat.lt_or_ge ms.length sol.length with
    | inl h => exact absurd hms (no_short_solution_h L (sol.length - 1) hno ms (by omega))
    | inr h => exact h⟩

end HeartGrid
""")
for lv in out:
    L = parse(lv['rows']); p, bl, he, wa, en, _ = L['start']; n = lv['n']
    lv['proof'] = 'kernel' if lv['states'] <= KERNEL_MAX_STATES else 'native'
    t = ['import HeartGrid.Prelude', GEN, 'namespace HeartGrid', '',
         '/-!\n  Room %d: %s  (minimum %d actions; search space %d states)\n\n' % (n, lv['name'], lv['opt'], lv['states'])
         + '\n'.join('  ' + r for r in lv['rows']) + '\n-/']
    ens = ', '.join('{ pos := (%d, %d), dir := %s, hunter := %s }' % (e[0], e[1], DIRN[e[2]], 'true' if e[3] else 'false') for e in en)
    t.append(f'/-- Room {n}, "{lv["name"]}": the map is in the comment above; the player enters at the arch. -/\ndef L{n} : Level where\n  h := {L["h"]}\n  w := {L["w"]}\n  walls := {pl(sorted(L["walls"]))}\n  exit := {L["exit"]}\n'
             f'  start := {{ player := {p}, blocks := {pl(bl)}, hearts := {pl(he)}, water := {pl(wa)},\n'
             f'             enemies := [{ens}], dead := false }}')
    t.append(f'/-- A winning move string for room {n} ({lv["opt"]} actions), found by the C++ breadth-first solver. -/\ndef sol{n} : List Act := acts "{lv["sol"]}"')
    t.append(f'/-- **Room {n} is solvable**: `sol{n}` really does win.  Checked by evaluating the rules in the kernel. -/\ntheorem L{n}_solves : Solves L{n} sol{n} := by decide +kernel')
    if lv['proof'] == 'kernel':
        t.append(f'/-- **Room {n} needs exactly {lv["opt"]} actions.**  The lower bound comes from `no_short_solution`,\nwith the exhaustive search evaluated by the kernel. -/\ntheorem L{n}_min : MinMoves L{n} {lv["opt"]} :=\n  minMoves_of L{n} sol{n} L{n}_solves (by decide +kernel)')
    else:
        t.append(f'/-- **Room {n} needs exactly {lv["opt"]} actions.**  The lower bound comes from `no_short_solution_h`,\nwith the exhaustive search ({lv["states"]} states) run as compiled code (`native_decide`). -/\ntheorem L{n}_min : MinMoves L{n} {lv["opt"]} :=\n  minMoves_of_h L{n} sol{n} L{n}_solves (by native_decide)')
    t += ['', 'end HeartGrid', '']
    open(f'HeartGrid/Rooms/R{n:02d}.lean', 'w').write('\n'.join(t))
imports = '\n'.join(f'import HeartGrid.Rooms.R{lv["n"]:02d}' for lv in out)
chain = ' ∧\n    '.join(f'MinMoves L{lv["n"]} {lv["opt"]}' for lv in out)
inc = ' ∧ '.join(f'{a["opt"]} < {b["opt"]}' for a, b in zip(out, out[1:]))
open('HeartGrid/Levels.lean', 'w').write(imports + '\n' + GEN + '\nnamespace HeartGrid\n\n'
    '/-- The whole curriculum: every room has an exact optimal length, and each is strictly longer than the last. -/\n'
    f'theorem curriculum :\n    {chain} ∧\n    ({inc}) :=\n'
    '  ⟨' + ', '.join(f'L{lv["n"]}_min' for lv in out) + ', by decide⟩\n\nend HeartGrid\n')
json.dump(out, open('levels.json', 'w'), indent=1)
open('web/levels.js', 'w').write('window.LEVELS = ' + json.dumps([{k: v for k, v in lv.items() if k != 'states'} | {'optimal': True} for lv in out]) + ';\n')
open('HeartGrid.lean', 'w').write('import HeartGrid.Rules\nimport HeartGrid.Bfs\nimport HeartGrid.BfsFast\nimport HeartGrid.Levels\n')
print('wrote Lean + JS')
